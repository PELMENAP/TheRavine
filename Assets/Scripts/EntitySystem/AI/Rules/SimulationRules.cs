    private ulong BuildEndogenousForbiddenMask()
    {
        ulong mask = 0UL;
        if (endogenousForbidden == null) return mask;
        for (int i = 0; i < endogenousForbidden.Length; i++)
        {
            int a = (int)endogenousForbidden[i];
            if ((uint)a < 64u) mask |= 1UL << a;
        }
        return mask;
    }

